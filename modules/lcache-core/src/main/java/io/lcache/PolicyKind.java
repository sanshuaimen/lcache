package io.lcache;

/**
 * 容量驱逐策略。仅当设置了 {@code maxSize > 0} 时生效。
 * <p>
 * 说明：为保持读路径无锁直读、不写任何共享顺序结构，两种策略的"顺序"都只在
 * 写线程/维护线程维护；读带来的热度和 LRU 语义通过"读计数采样 + 周期性提升"近似，
 * 而不是每次读都移动链表（避免读路径写共享内存）。
 *
 * <ul>
 *   <li>{@link #FIFO}：按插入顺序淘汰（被替换时不移位）。</li>
 *   <li>{@link #LRU}：近似最近最少使用——插入/更新移到队尾，且周期性把"近期被
 *       频繁读到"的条目提升到队尾再淘汰队头。</li>
 * </ul>
 */
public enum PolicyKind {
    /** 先进先出：按插入顺序淘汰。 */
    FIFO,
    /** 近似 LRU：插入/更新 + 读采样提升后再淘汰最老。 */
    LRU
}
